"""Export the Python rule base to docs/rules.js for the GitHub Pages build.

engine/rules.py (+ the extraction tables in engine/extract.py) stay the single
source of truth. Run this after editing them:

    python tools/export_rules.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine import extract, rules  # noqa: E402

data = {
    "VECTORS": rules.VECTORS,
    "FAMILIES": {k: [list(s) for s in v] for k, v in rules.FAMILIES.items()},
    "BEHAVIOURS": [{**b, **({"mobile": list(b["mobile"])} if "mobile" in b else {})} for b in rules.BEHAVIOURS],
    "DYNAMIC_SIGNALS": [list(s) for s in rules.DYNAMIC_SIGNALS],
    "NOISE_NETS": extract.NOISE_NETS,
    "NOISE_DOMAINS": list(extract.NOISE_DOMAINS),
    "KNOWN_DEFAULT_CREDS": list(extract.KNOWN_DEFAULT_CREDS),
}

out = ROOT / "docs" / "rules.js"
out.parent.mkdir(exist_ok=True)
out.write_text(
    "// GENERATED by tools/export_rules.py from engine/rules.py - do not edit by hand.\n"
    "(function (root) {\n"
    f"  const RULES = {json.dumps(data, indent=2)};\n"
    "  if (typeof module !== 'undefined' && module.exports) module.exports = RULES;\n"
    "  else root.GPON_RULES = RULES;\n"
    "})(typeof self !== 'undefined' ? self : this);\n",
    encoding="utf-8",
)
print(f"wrote {out.relative_to(ROOT)}")
